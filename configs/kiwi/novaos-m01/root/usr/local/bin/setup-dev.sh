#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# Prepare NovaWorkspace for developing the Nova ecosystem on NovaOS.
set -euo pipefail

USER_HOME="${HOME:-/home/nova}"
WS="${NOVA_WORKSPACE:-${USER_HOME}/NovaWorkspace}"

dirs=(
  NovaOS
  NovaDocs
  NovaStudio
  NovaCloud
  NovaAI
)

echo "==> NovaOS Developer Edition — setup-dev"
echo "    workspace: ${WS}"

mkdir -p "${WS}"
for d in "${dirs[@]}"; do
  mkdir -p "${WS}/${d}"
  if [[ ! -e "${WS}/${d}/README.md" && ! -d "${WS}/${d}/.git" ]]; then
    printf '# %s workspace\n' "${d}" > "${WS}/${d}/README.md"
  fi
done

cat > "${WS}/README.md" <<EOF
# NovaWorkspace

Generated by setup-dev.sh.

| Directory | Suggested use |
|-----------|----------------|
| NovaOS | This OS / platform repo |
| NovaDocs | Documentation product |
| NovaStudio | Creative / IDE product |
| NovaCloud | Cloud services |
| NovaAI | AI core |

Clone example:

\`\`\`bash
cd ~/NovaWorkspace/NovaOS
git clone https://github.com/NovaEcosystemOfficial/NovaOS.git .
\`\`\`
EOF

if command -v flatpak >/dev/null 2>&1; then
  flatpak remote-add --if-not-exists --user flathub https://flathub.org/repo/flathub.flatpakrepo 2>/dev/null || true
fi

if command -v xdg-settings >/dev/null 2>&1 && [[ -f /usr/share/applications/firefox.desktop ]]; then
  xdg-settings set default-web-browser firefox.desktop 2>/dev/null || true
fi

echo "OK: NovaWorkspace ready at ${WS}"
ls -la "${WS}"
